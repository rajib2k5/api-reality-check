import decimal, datetime, fractions, array, struct, io, threading, queue, collections, uuid, ipaddress, zoneinfo
d = decimal.Decimal("1.55")
print(d.quantize(decimal.Decimal("0.1"), rounding=decimal.ROUND_HALF_UP), d.as_tuple().exponent, d.is_nan())
dt = datetime.datetime(2020, 1, 2, 3, 4)
print(dt.replace(tzinfo=datetime.timezone.utc), dt.isocalendar().week, dt.timestamp(), dt.fold, dt.tzinfo)
dd = datetime.date(2020, 1, 1)
print(dd.isoformat(), dd.toordinal(), dd.weekday(), dd.year)
td = datetime.timedelta(days=1)
print(td.total_seconds(), td.days, td.seconds)
f = fractions.Fraction(1, 3)
print(f.limit_denominator(max_denominator=10), f.numerator, f.as_integer_ratio())
a = array.array("i", [1, 2])
print(a.tobytes(), a.itemsize, a.typecode)
st = struct.Struct("i")
print(st.size, st.format, st.pack(1))
b = io.BytesIO(b"x")
print(b.getbuffer().nbytes, b.closed, b.read())
e = threading.Event()
print(e.wait(timeout=0.01), e.is_set())
q = queue.Queue(maxsize=2)
q.put(1, block=False)
print(q.qsize(), q.maxsize, q.get(timeout=1))
dq = collections.deque([1], maxlen=2)
print(dq.maxlen)
u = uuid.UUID(int=1)
print(u.hex, u.version, u.int)
ip = ipaddress.ip_address("10.0.0.1")
n = ipaddress.IPv4Network("10.0.0.0/8")
print(ip.is_private, n.num_addresses, n.prefixlen)
z = zoneinfo.ZoneInfo("UTC")
print(z.key)
od = collections.OrderedDict(a=1)
print(od.popitem(last=False))
