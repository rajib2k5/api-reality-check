import pandas as pd
ts = pd.Timestamp("2024-01-05")
print(ts.day_name(), ts.dayofweek, ts.normalize(), ts.to_pydatetime(), ts.tz_localize(tz="UTC").tz_convert("US/Eastern"))
td = pd.Timedelta(hours=3)
print(td.total_seconds(), td.components.hours)
idx = pd.Index([1, 2])
print(idx.to_list(), idx.is_unique, idx.get_loc(2))
p = pd.Period("2024-01", freq="M")
print(p.start_time, p.end_time)
s = pd.Series([1, 2], index=["a", "b"])
print(s.idxmax(), s.cumsum(), s.shift(periods=1, fill_value=0), s.rename("x").to_frame(name="y"), s.nlargest(n=1), s.dt if False else s.index)
df = pd.DataFrame({"a": [1, 2], "b": [3, 4]})
print(df.plot if False else 0, df.assign(c=lambda d: d.a + d.b).query("c > 3").eval("d = a * 2"), df.melt(id_vars=["a"]), df.T, df.columns.tolist(), df.a.sum())
print(df.groupby("a")["b"].transform("sum"), df.set_index("a").loc[1, "b"], df.select_dtypes(include="number").corr(method="pearson"))
print(df.to_json(orient="records", lines=True), df.drop(columns=["b"]).rename(columns={"a": "z"}), df.sample(n=1, random_state=0), df.memory_usage(deep=True))
print(df.iterrows(), list(df.itertuples(index=False, name="R")), df.empty, df.shape, df.ndim, df.size, df.values, df.dtypes, df.attrs)
